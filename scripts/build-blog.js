function generatePostPages(posts) {
  if (path.dirname(BLOG_OUTPUT_DIR) !== ROOT_DIR) {
    throw new Error(`Refusing to replace unexpected blog output directory: ${BLOG_OUTPUT_DIR}`);
  }

  fs.rmSync(BLOG_OUTPUT_DIR, { recursive: true, force: true });
  ensureDir(BLOG_OUTPUT_DIR);

  posts.filter((post) => post.isReady).forEach((post) => {
    const outputDir = path.join(BLOG_OUTPUT_DIR, post.slug);
    ensureDir(outputDir);
    fs.writeFileSync(path.join(outputDir, "index.html"), postPageHtml(post));
  });
}

function fileDateString(filePath) {
  try {
    return fs.statSync(filePath).mtime.toISOString().slice(0, 10);
  } catch (error) {
    return pacificToday();
  }
}

function collectSitemapEntries(posts) {
  const entries = new Map();
  const add = (route, lastmod, priority = "0.7") => {
    entries.set(route, { route, lastmod, priority });
  };

  fs.readdirSync(ROOT_DIR, { withFileTypes: true }).forEach((entry) => {
    const fullPath = path.join(ROOT_DIR, entry.name);

    if (entry.isFile() && entry.name.endsWith(".html") && !SITEMAP_EXCLUDED_FILES.has(entry.name)) {
      const route = entry.name === "index.html" ? "/" : `/${path.basename(entry.name, ".html")}`;
      add(route, fileDateString(fullPath), route === "/" ? "1.0" : route === "/blog" ? "0.9" : "0.7");
      return;
    }

    if (!entry.isDirectory() || SITEMAP_EXCLUDED_DIRS.has(entry.name)) return;
    const indexPath = path.join(fullPath, "index.html");
    if (fs.existsSync(indexPath)) add(`/${entry.name}/`, fileDateString(indexPath));
  });

  posts.filter((post) => post.isReady).forEach((post) => {
    add(`/blog/${post.slug}/`, post.dateModified.slice(0, 10), "0.8");
  });

  return Array.from(entries.values()).sort((a, b) => a.route.localeCompare(b.route));
}

function writeSitemap(posts) {
  const entries = collectSitemapEntries(posts);
  const rows = entries.map((entry) => `  <url>
    <loc>${escapeHtml(`${SITE_URL}${entry.route}`)}</loc>
    <lastmod>${entry.lastmod}</lastmod>
    <priority>${entry.priority}</priority>
  </url>`).join("\n");
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${rows}
</urlset>
`;
  fs.writeFileSync(SITEMAP_FILE, xml);
}

function buildBlog() {
  ensureDir(path.dirname(OUTPUT_FILE));
  const posts = readPosts();
  const publicPosts = posts.map(publicPost);

  fs.writeFileSync(OUTPUT_FILE, `${JSON.stringify(publicPosts, null, 2)}\n`);
  generatePostPages(posts);
  writeSitemap(posts);

  const readyCount = posts.filter((post) => post.isReady).length;
  console.log(`Built ${posts.length} blog record(s) and ${readyCount} static blog page(s).`);
}

buildBlog();
